#include<bits/stdc++.h>
using i64 = long long;
void solve()
{
    i64 p;
    std::cin >> p;
    std::cout << 6 * p << " 3\n";
    std::cout << p << " " << 2 * p << " " << 3 * p << "\n";
}
int main()
{
    std::ios::sync_with_stdio(false);
    std::cin.tie(nullptr);
    int t;
    std::cin >> t;
    while (t--) {
        solve();
    }
    return 0;
}
			  		 		     		 		      				